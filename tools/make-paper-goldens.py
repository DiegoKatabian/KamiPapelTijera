"""Writes tools/paper-tests/Goldens.g.cs: numbers from the Python reference (tools/paper_core.py) that the C# paper
core must reproduce (spec 025 D38). Run by tools/run-paper-tests.py before every test run, so the goldens always come
from the current reference.

    python tools/make-paper-goldens.py
"""
import json
import math
import os
import sys

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, 'tools'))
import paper_core as pc  # noqa: E402

OUT = os.path.join(ROOT, 'tools', 'paper-tests', 'Goldens.g.cs')
THICKNESS = [1.5, 2.0, 3.0, 2.5]  # per leaf kind, exercised by the goldens
TIMES = [0.0, 0.07, 0.13, 0.25, 0.37, 0.5, 0.63, 0.81, 0.93, 1.0]


def arr(values):
    return 'new double[] { ' + ', '.join(repr(float(v)) for v in values) + ' }'


def pieces():
    """Synthetic pieces covering every leaf and both kinds, in canonical coordinates (start side +x)."""
    def box(x0, x1, y0, y1, z0, z1):
        return [(x, y, z) for x in (x0, x1) for y in (y0, y1) for z in (z0, z1)]
    out = []
    # name, kind, leaf, corners
    out.append(('card_front', pc.CARD, pc.SHEET_FRONT, box(10, 14, 1.0, 9.0, -0.1, 0.1)))
    out.append(('volume_front', pc.VOLUME, pc.SHEET_FRONT, box(20, 26, 1.0, 12.0, -3, 3)))
    out.append(('wide_volume_front', pc.VOLUME, pc.SHEET_FRONT, box(5, 30, 1.0, 4.0, -8, 8)))
    out.append(('card_end', pc.CARD, pc.END_STATIC, box(-18, -12, 1.0, 7.0, 4.9, 5.1)))
    out.append(('volume_end', pc.VOLUME, pc.END_STATIC, box(-40, -33, 1.0, 15.0, -2, 2)))
    out.append(('card_start', pc.CARD, pc.START_STATIC, box(3, 8, 0.8, 6.0, -0.2, 0.2)))
    out.append(('volume_start', pc.VOLUME, pc.START_STATIC, box(25, 31, 1.0, 10.0, 1, 6)))
    out.append(('card_back', pc.CARD, pc.SHEET_BACK, box(-22, -19, 1.0, 8.0, -0.1, 0.1)))
    out.append(('volume_back', pc.VOLUME, pc.SHEET_BACK, box(-12, -6, 1.0, 13.0, -4, 4)))
    return out


def main():
    data = json.load(open(os.path.join(ROOT, 'tools', 'data', 'paper-book-level2.json')))
    fit = json.load(open(os.path.join(ROOT, 'tools', 'data', 'paper-curl.json')))
    S = np.array(data['profiles']['right'])
    E = np.array(data['profiles']['left'])
    params = pc.CurlParams(fit['lead'], fit['ease'], fit['duration'], fit['shape'])
    curl = pc.Curl(pc.Profile(S), pc.Profile(E), params)
    lines = ['// Generated by tools/make-paper-goldens.py from tools/paper_core.py. Do not edit.',
             'namespace Kami.Paper.Tests', '{', '    public static class Goldens', '    {']
    lines.append(f'        public static readonly double[] StartX = {arr(S[:, 0])};')
    lines.append(f'        public static readonly double[] StartY = {arr(S[:, 1])};')
    lines.append(f'        public static readonly double[] EndX = {arr(E[:, 0])};')
    lines.append(f'        public static readonly double[] EndY = {arr(E[:, 1])};')
    lines.append(f'        public static readonly double Lead = {fit["lead"]!r}, Ease = {fit["ease"]!r}, Shape = {fit["shape"]!r}, Duration = {fit["duration"]!r};')
    lines.append(f'        public static readonly double[] Times = {arr(TIMES)};')
    lines.append(f'        public static readonly double[] Thickness = {arr(THICKNESS)};')

    prof = pc.Profile(S)
    probes = [0.0, 0.3, 1.7, 12.5, 30.0, prof.length - 0.01, prof.length + 5]
    lines.append(f'        public static readonly double[] ProfileProbes = {arr(probes)};')
    lines.append(f'        public static readonly double[] ProfileAngle = {arr([prof.angle(u) for u in probes])};')
    lines.append(f'        public static readonly double[] ProfilePointX = {arr([prof.point(u)[0] for u in probes])};')
    lines.append(f'        public static readonly double[] ProfilePointY = {arr([prof.point(u)[1] for u in probes])};')
    xprobes = [-1.0, 0.0, 0.25, 5.3, 44.0, 60.0]
    lines.append(f'        public static readonly double[] XoProbes = {arr(xprobes)};')
    lines.append(f'        public static readonly double[] ProfileU = {arr([prof.u_at(x) for x in xprobes])};')
    lines.append(f'        public static readonly double[] ProfileHeight = {arr([prof.height(x) for x in xprobes])};')

    # the curl at every time: x and y of every point, flattened
    cx, cy, ca = [], [], []
    for t in TIMES:
        pts, ang = curl.points(t)
        cx += list(pts[:, 0])
        cy += list(pts[:, 1])
        ca += list(ang)
    lines.append(f'        public static readonly double[] CurlX = {arr(cx)};')
    lines.append(f'        public static readonly double[] CurlY = {arr(cy)};')
    lines.append(f'        public static readonly double[] CurlAngle = {arr(ca)};')

    # pieces through the turn, solved in sequence (the monotonic state matters)
    model = pc.TurnModel(curl, 1)
    model.thickness = list(THICKNESS)
    ps = pieces()
    objs = []
    for name, kind, leaf, corners in ps:
        piece = pc.Piece(kind, leaf, corners)
        model.prepare(piece)
        objs.append(piece)
    mats = []
    folds = []
    for t in TIMES:
        model.set_time(t)
        for piece in objs:
            m = model.solve(piece)
            mats += list(m[:3, :3].reshape(-1)) + list(m[:3, 3])
            folds += [piece.last[0], piece.last[1], 1.0 if piece.last[2] else 0.0]
    lines.append(f'        public static readonly string[] PieceNames = new string[] {{ {", ".join(chr(34) + n + chr(34) for n, *_ in ps)} }};')
    lines.append(f'        public static readonly int[] PieceKinds = new int[] {{ {", ".join(str(k) for _, k, _, _ in ps)} }};')
    lines.append(f'        public static readonly int[] PieceLeaves = new int[] {{ {", ".join(str(l) for _, _, l, _ in ps)} }};')
    lines.append(f'        public static readonly double[] PieceCorners = {arr([v for _, _, _, c in ps for p in c for v in p])};')
    lines.append(f'        public static readonly double[] PieceMatrices = {arr(mats)};')
    lines.append(f'        public static readonly double[] PieceFolds = {arr(folds)};')
    lines += ['    }', '}', '']
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, 'w', encoding='utf-8').write('\n'.join(lines))
    print(f'[make-paper-goldens] {len(ps)} pieces x {len(TIMES)} times -> {os.path.relpath(OUT, ROOT)}')


if __name__ == '__main__':
    main()
